/**
 * Resolves each catalog event's qlooRefs to Qloo IDs and writes data/qloo-mappings.json.
 * Records whether each mapping is direct (the event *is* that film / the tag names the activity)
 * or approximate (a "for fans of" artist used as an audience proxy, or a near-match tag).
 * Unmatched refs are recorded too; those events stay discoverable through normal browsing.
 *
 * Run once after changing the catalog: npm run qloo:map
 */
import { readFileSync, writeFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^(\w+)=(.*)$/);
  if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
}
const BASE = (process.env.QLOO_API_URL ?? "https://hackathon.api.qloo.com").replace(/\/$/, "");
const KEY = process.env.QLOO_API_KEY!;
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function get<T>(path: string, params: Record<string, string>): Promise<T> {
  await sleep(300); // stay well under 5 req/s
  const res = await fetch(`${BASE}${path}?${new URLSearchParams(params)}`, { headers: { "X-Api-Key": KEY } });
  if (!res.ok) throw new Error(`${path} ${res.status}`);
  return res.json() as Promise<T>;
}

type Ref = { name: string; type: "artist" | "movie" | "book" | "place" | "tag"; relation?: string };
type Mapping =
  | { ref: Ref; match: "direct" | "approximate"; qlooId: string; qlooName: string; qlooType: string; note: string }
  | { ref: Ref; match: "unmatched"; note: string };

const norm = (s: string) => s.toLowerCase().replace(/[^a-z0-9]/g, "");

async function resolve(ref: Ref): Promise<Mapping> {
  if (ref.type === "tag") {
    const body = await get<{ results?: { tags?: { id?: string; tag_id?: string; name: string }[] } }>("/v2/tags", { "filter.query": ref.name, take: "8" });
    const tags = (body.results?.tags ?? []).map((t) => ({ id: t.id ?? t.tag_id!, name: t.name }));
    // Prefer genre/category/activity tags over keyword/amenity tags.
    const rank = (id: string) => (/:genre:/.test(id) ? 0 : /:category:|:activities:|:subgenre:/.test(id) ? 1 : 2);
    const sorted = tags.sort((a, b) => rank(a.id) - rank(b.id));
    const exact = sorted.find((t) => norm(t.name) === norm(ref.name));
    const best = exact ?? sorted[0];
    if (!best) return { ref, match: "unmatched", note: "No Qloo tag found" };
    return {
      ref,
      match: exact ? "direct" : "approximate",
      qlooId: best.id,
      qlooName: best.name.trim(),
      qlooType: "tag",
      note: exact ? "Tag name matches the event attribute" : `Closest Qloo tag to “${ref.name}”`,
    };
  }
  const body = await get<{ results?: { entity_id: string; name: string; subtype?: string }[] }>("/search", { query: ref.name, types: `urn:entity:${ref.type}`, take: "3" });
  const hit = (body.results ?? []).find((r) => norm(r.name) === norm(ref.name));
  if (!hit) return { ref, match: "unmatched", note: "No exact-name Qloo entity" };
  const direct = ref.relation === "screening" || ref.relation === "venue";
  return {
    ref,
    match: direct ? "direct" : "approximate",
    qlooId: hit.entity_id,
    qlooName: hit.name,
    qlooType: `urn:entity:${ref.type}`,
    note: direct ? "The event screens this film" : "Organizer-provided “for fans of” reference, used as an audience proxy (the artist is not performing)",
  };
}

async function main() {
  const catalog = JSON.parse(readFileSync("data/catalog.json", "utf8")) as { events: { id: string; qlooRefs: Ref[] }[] };
  const unique = new Map<string, Ref>();
  for (const e of catalog.events) for (const r of e.qlooRefs) unique.set(`${r.type}:${r.name}:${r.relation ?? ""}`, r);
  const refs: Record<string, Mapping> = {};
  for (const [key, ref] of unique) {
    try {
      refs[key] = await resolve(ref);
    } catch (err) {
      refs[key] = { ref, match: "unmatched", note: `Lookup failed: ${(err as Error).message}` };
    }
    const m = refs[key];
    console.log(`${m.match.padEnd(11)} ${key}${"qlooName" in m ? ` → ${m.qlooName} (${m.qlooId})` : ""}`);
  }
  const byEvent = Object.fromEntries(catalog.events.map((e) => [e.id, e.qlooRefs.map((r) => `${r.type}:${r.name}:${r.relation ?? ""}`)]));
  writeFileSync("data/qloo-mappings.json", JSON.stringify({ _note: "Generated by scripts/qloo-map.ts. match: direct | approximate | unmatched.", generatedAt: new Date().toISOString(), refs, byEvent }, null, 1));
}

main();
