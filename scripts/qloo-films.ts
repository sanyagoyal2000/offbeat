/**
 * Fetches facts for the real films used in sample screenings from Qloo and writes data/films.json:
 * Qloo id, title, year, description, genres and the image URL Qloo provides (Qloo has no runtime).
 * Nothing here is typed by hand, so details stay grounded in Qloo's data.
 * Run: npm run qloo:films (then npm run catalog:generate && npm run qloo:map)
 */
import { readFileSync, writeFileSync } from "node:fs";

for (const line of readFileSync(".env.local", "utf8").split("\n")) {
  const m = line.match(/^(\w+)=(.*)$/);
  if (m && !process.env[m[1]]) process.env[m[1]] = m[2];
}
const BASE = (process.env.QLOO_API_URL ?? "https://hackathon.api.qloo.com").replace(/\/$/, "");
const KEY = process.env.QLOO_API_KEY!;
const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

/** id → search title, language of the original film. */
export const FILMS: { id: string; query: string; year: number; language: string }[] = [
  { id: "3-idiots", query: "3 Idiots", year: 2009, language: "Hindi" },
  { id: "zindagi-na-milegi-dobara", query: "Zindagi Na Milegi Dobara", year: 2011, language: "Hindi" },
  { id: "dangal", query: "Dangal", year: 2016, language: "Hindi" },
  { id: "lagaan", query: "Lagaan", year: 2001, language: "Hindi" },
  { id: "dil-chahta-hai", query: "Dil Chahta Hai", year: 2001, language: "Hindi" },
  { id: "andhadhun", query: "Andhadhun", year: 2018, language: "Hindi" },
  { id: "gully-boy", query: "Gully Boy", year: 2019, language: "Hindi" },
  { id: "taare-zameen-par", query: "Taare Zameen Par", year: 2007, language: "Hindi" },
  { id: "kumbalangi-nights", query: "Kumbalangi Nights", year: 2019, language: "Malayalam" },
  { id: "the-lunchbox", query: "The Lunchbox", year: 2013, language: "Hindi" },
  { id: "paddington-2", query: "Paddington 2", year: 2017, language: "English" },
  { id: "before-sunrise", query: "Before Sunrise", year: 1995, language: "English" },
];

type Ent = {
  entity_id: string;
  name: string;
  properties?: { release_year?: number; duration?: number; description?: string; image?: { url?: string } };
  tags?: { name: string; type?: string; id?: string }[];
};

async function main() {
  const out: Record<string, unknown> = {};
  for (const f of FILMS) {
    await sleep(300);
    const res = await fetch(`${BASE}/search?${new URLSearchParams({ query: f.query, types: "urn:entity:movie", take: "5" })}`, { headers: { "X-Api-Key": KEY } });
    const body = (await res.json()) as { results?: Ent[] };
    const hits = body.results ?? [];
    // Prefer the exact title from the expected year.
    const hit = hits.find((h) => h.name.toLowerCase() === f.query.toLowerCase() && h.properties?.release_year === f.year) ?? hits.find((h) => h.properties?.release_year === f.year);
    if (!hit) {
      console.log(`unmatched  ${f.query} (${f.year})`);
      out[f.id] = { id: f.id, title: f.query, year: f.year, language: f.language, qlooId: null };
      continue;
    }
    const genres = (hit.tags ?? []).filter((t) => (t.type ?? t.id ?? "").includes("genre")).map((t) => t.name).slice(0, 3);
    out[f.id] = {
      id: f.id,
      title: f.query, // commonly used title; Qloo's canonical name kept below
      qlooName: hit.name,
      year: hit.properties?.release_year ?? f.year,
      language: f.language,
      description: hit.properties?.description ?? null,
      image: hit.properties?.image?.url ?? null,
      genres,
      qlooId: hit.entity_id,
    };
    console.log(`matched    ${f.query} → ${hit.name} (${hit.properties?.release_year}) ${hit.properties?.image?.url ? "[image]" : "[no image]"} ${genres.join(", ")}`);
  }
  writeFileSync("data/films.json", JSON.stringify({ _note: "Generated by scripts/qloo-films.ts from Qloo. Images are Qloo-provided URLs, shown with credit.", films: out }, null, 1));
}

main();
